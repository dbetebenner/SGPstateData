### widaACCESS_pl_to_ss
###
### Thin convenience wrapper around widaACCESS_ss_to_pl() for the reverse direction
### (proficiency level -> integer scale score).  See widaACCESS_ss_to_pl() for the
### `position` / `hoss` semantics.
###
### Defined FIRST (before widaACCESS_ss_to_pl) so widaACCESS_ss_to_pl() remains the
### LAST top-level expression in this file (useful when sourcing for value).  SGPstateData
### loads both functions via sys.source(..., envir = new.env()) + get(), so call-site
### access should use SGP_Configuration$widaACCESS_ss_to_pl / widaACCESS_pl_to_ss.
### The wrapper resolves widaACCESS_ss_to_pl at call time, so defining it earlier is safe.

widaACCESS_pl_to_ss <- function(
    grade=NULL,
    proficiency_level=NULL,
    scale=c("OLD", "NEW"),
    position=c("min", "max", "middle"),
    hoss=NULL
) {
    widaACCESS_ss_to_pl(
        grade=grade,
        scale=scale,
        proficiency_level=proficiency_level,
        position=match.arg(position),
        hoss=hoss)
}

### widaACCESS_ss_to_pl
###
### Converts between a WIDA ACCESS composite scale score and its associated
### 1.0-6.0 performance level (PL), in EITHER direction, for the pre-2025-26 (OLD)
### or the 2025-26 (NEW) composite scale (selected via the `scale` argument).
###
### DIRECTIONS (supply exactly one input):
###   * Forward (scale score -> PL): pass `scale_score`.  Returns the PL band that
###     contains each score.  This is the original, unchanged behavior.
###   * Reverse (PL -> integer scale score): pass `proficiency_level`.  Because a PL
###     occupies the half-open score band [LOW_SCORE, HIGH_SCORE), `position` selects
###     which integer score in that band to return:
###       - "min"    (default) smallest integer in the band = the level's lower cut
###       - "max"              largest integer below the next level's cut
###       - "middle"           round-half-up midpoint of [min, max]
###     On the OLD scale the top band is closed at the official ceiling (600), so
###     "max"/"middle" for PL 6.0 are well defined.  On the (PRELIMINARY) NEW scale the
###     top band is still open (a 999 sentinel HIGH_SCORE), so "max"/"middle" for the
###     top level return NA unless `hoss` supplies the highest obtainable scale score
###     (a scalar applied to every top band, or a numeric vector named by grade).  A PL
###     that does not exist for a grade (e.g. 6.0 at grade 0 on the NEW scale) returns NA.
###
### Both directions are vectorized over `grade` and the score/level input.
###
### NOTE (PRELIMINARY NEW-SCALE CUTS):
###   WIDA reset the composite scale in 2025-26.  The range is still 100-600 but
###   the new scale is NOT comparable to the old one.  The NEW-scale PL bands
###   embedded below are PRELIMINARY -- they are derived from the 2025-26 / 2024-25
###   concordance table and are stand-ins ONLY until WIDA conducts standard setting
###   in Summer 2026 to establish official cuts.  When the official cuts are released
###   (target: Fall 2026), replace the NEW-scale lookup block below and delete this
###   NOTE.

